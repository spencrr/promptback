import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { PromptSearchEngine } from '../src/engine.js';
import { sessionOpenTargets } from '../src/links.js';
import { classifyClaudeOrigin, listClaudeSessionFiles, readClaudeSession } from '../src/sources/claudeCode.js';

let tmp: string;
let home: string;

const SID = '4381a2ec-673e-4e7d-b24b-2a42833e0059';

function line(obj: Record<string, unknown>): string {
	return JSON.stringify(obj);
}

function user(content: unknown, extra: Record<string, unknown> = {}): string {
	return line({
		parentUuid: null,
		isSidechain: false,
		userType: 'external',
		cwd: 'C:\\src\\webapp',
		sessionId: SID,
		version: '2.1.281',
		gitBranch: 'main',
		type: 'user',
		message: { role: 'user', content },
		uuid: extra.uuid ?? `u-${Math.random().toString(36).slice(2, 8)}`,
		timestamp: '2026-10-10T07:50:37.000Z',
		entrypoint: 'cli',
		...extra,
	});
}

beforeEach(() => {
	tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'promptback-claude-'));
	home = path.join(tmp, '.claude');
	const project = path.join(home, 'projects', 'C--src-webapp');
	fs.mkdirSync(project, { recursive: true });
	fs.writeFileSync(
		path.join(project, `${SID}.jsonl`),
		[
			line({
				type: 'queue-operation',
				operation: 'enqueue',
				sessionId: SID,
				timestamp: '2026-10-10T07:50:36.000Z',
			}),
			user([{ type: 'text', text: 'Please explain the high-level architecture of this repo' }], {
				uuid: 'u1',
				timestamp: '2026-10-10T07:50:37.000Z',
			}),
			line({
				type: 'assistant',
				uuid: 'a1',
				timestamp: '2026-10-10T07:50:40.000Z',
				message: { role: 'assistant', model: 'claude-opus-5-5', content: [{ type: 'text', text: 'Sure.' }] },
			}),
			user([{ type: 'tool_result', tool_use_id: 't1', content: 'file contents' }], { uuid: 'u2' }),
			user('<task-notification>\n<task-id>abc</task-id>\n</task-notification>', {
				uuid: 'u3',
				turnOrigin: 'task_notification',
			}),
			user('<command-name>/clear</command-name>', { uuid: 'u4' }),
			user('Summarize the tests for the subagent', { uuid: 'u5', isSidechain: true }),
			user('Caveat: the messages below were generated by the user while running local commands.', {
				uuid: 'u6',
				isMeta: true,
			}),
			user('Now add a regression test for the parser', { uuid: 'u7', timestamp: '2026-10-10T08:00:00.000Z' }),
			line({ type: 'ai-title', aiTitle: 'Architecture walkthrough', sessionId: SID }),
			line({ type: 'last-prompt', lastPrompt: 'Now add…', sessionId: SID }),
			'',
		].join('\n'),
	);
	// A file with no prompts at all is tracked but produces no session.
	fs.writeFileSync(
		path.join(project, 'empty-session.jsonl'),
		`${line({ type: 'mode', mode: 'normal', sessionId: 'empty-session' })}\n`,
	);
});

afterEach(() => {
	fs.rmSync(tmp, { recursive: true, force: true });
});

describe('Claude Code source', () => {
	it('lists project session files', () => {
		expect(
			listClaudeSessionFiles(home)
				.map(f => f.sessionId)
				.sort((a, b) => a.localeCompare(b)),
		).toEqual([SID, 'empty-session']);
		expect(listClaudeSessionFiles(path.join(tmp, 'nowhere'))).toEqual([]);
	});

	it('projects user messages to prompts with origins, model, title and repository metadata', () => {
		const [file] = listClaudeSessionFiles(home).filter(f => f.sessionId === SID);
		const r = readClaudeSession(file!, fs.statSync(file!.path).size);
		expect(r.error).toBeUndefined();
		expect(r.prompts.map(p => [p.id.split(':').at(-1), p.origin])).toEqual([
			['u1', 'human'],
			['u3', 'system'],
			['u4', 'system'],
			['u5', 'agent'],
			['u6', 'system'],
			['u7', 'human'],
		]);
		// The first prompt is answered by the first assistant turn; later ones carry the latest model seen.
		expect(r.prompts.every(p => p.model === 'claude-opus-5-5')).toBe(true);
		expect(r.prompts[0]!.timestamp).toBe(Date.parse('2026-10-10T07:50:37.000Z'));
		expect(r.prompts.map(p => p.seq)).toEqual([0, 1, 2, 3, 4, 5]);
		expect(r.session).toMatchObject({
			key: `claude-code:${SID}`,
			source: 'claude-code',
			sessionId: SID,
			title: 'Architecture walkthrough',
			cwd: 'C:\\src\\webapp',
			branch: 'main',
			client: 'claude/cli',
			// Timestamps come from the lines that are read (messages and titles), not from bookkeeping lines.
			createdAt: Date.parse('2026-10-10T07:50:37.000Z'),
			updatedAt: Date.parse('2026-10-10T08:00:00.000Z'),
		});
	});

	it('classifies injected and sidechain messages', () => {
		expect(classifyClaudeOrigin({}, 'Fix the bug')).toBe('human');
		expect(classifyClaudeOrigin({}, '<system-reminder>Be brief.</system-reminder>')).toBe('system');
		expect(classifyClaudeOrigin({}, '<local-command-stdout>ok</local-command-stdout>')).toBe('system');
		expect(classifyClaudeOrigin({}, '<ide_opened_file>x.ts</ide_opened_file>')).toBe('system');
		expect(classifyClaudeOrigin({ isSidechain: true }, 'Research X')).toBe('agent');
		expect(classifyClaudeOrigin({ promptSource: 'sdk' }, 'Research X')).toBe('agent');
		expect(classifyClaudeOrigin({ isMeta: true }, 'anything')).toBe('system');
		// A human prompt that happens to start with markup is not an injected message.
		expect(classifyClaudeOrigin({}, '<div class="x"> renders wrong, why?')).toBe('human');
	});

	it('indexes through the engine, filters by source and client, and offers a resume command', async () => {
		const engine = PromptSearchEngine.open({
			indexDir: path.join(tmp, 'index'),
			sources: {
				copilot: { enabled: false },
				'vscode-chat': { enabled: false },
				'agent-host': { enabled: false },
				'claude-code': { home },
				codex: { enabled: false },
			},
			embedding: { kind: 'none' },
		});
		try {
			const r = await engine.sync();
			expect(r.errors).toEqual([]);
			expect(r.addedPrompts).toBe(6);
			expect(engine.status().promptsBySource).toEqual({ 'claude-code': 6 });
			const hits = (await engine.search('architecture src:claude')).hits;
			expect(hits).toHaveLength(1);
			expect(hits[0]!.session.client).toBe('claude/cli');
			expect((await engine.search('architecture client:claude')).hits).toHaveLength(1);
			expect((await engine.search('architecture client:cli')).hits).toHaveLength(0);
			// Only the user's own prompts by default; injected ones stay keyword-searchable with from:any.
			expect((await engine.search('task-notification')).hits).toHaveLength(0);
			expect((await engine.search('task-notification from:any')).hits).toHaveLength(1);
			const targets = sessionOpenTargets(hits[0]!.session);
			expect(targets).toEqual([
				{
					kind: 'terminal-resume',
					label: 'Resume with Claude Code',
					command: `claude --resume ${SID}`,
					cwd: 'C:\\src\\webapp',
				},
			]);

			// Appending a prompt re-reads the file; deleting it removes the session.
			const file = path.join(home, 'projects', 'C--src-webapp', `${SID}.jsonl`);
			fs.appendFileSync(
				file,
				`${user('Also update the README', { uuid: 'u8', timestamp: '2026-10-10T08:05:00.000Z' })}\n`,
			);
			expect((await engine.sync()).addedPrompts).toBe(1);
			expect((await engine.sync()).addedPrompts).toBe(0);
			fs.rmSync(file);
			expect((await engine.sync()).removedPrompts).toBe(7);
		} finally {
			await engine.close();
		}
	});
});
